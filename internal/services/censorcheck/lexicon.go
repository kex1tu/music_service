// isDrugPlanContext проверяет, используется ли слово "план" в контексте психоактивных веществ,
// либо как нейтральное житейское слово (бизнес-план, по плану, строить планы).
func isDrugPlanContext(word, line string) bool {
	w := strings.ToLower(strings.TrimSpace(word))
	switch w {
	case "план", "плана", "плану", "планом", "планчик", "планчика":
		lineLower := strings.ToLower(line)
		for _, pat := range nonDrugPlanPatterns {
			if pat.MatchString(lineLower) {
				return false
			}
		}
		return true
	default:
		return true
	}
}

// classifyWord определяет категорию триггерного слова или возвращает false, если слово нейтральное.
func classifyWord(word string) (SpotCategory, bool) {
	w := strings.ToLower(strings.TrimSpace(word))
	if w == "" {
		return "", false
	}
	for _, stem := range []string{"суицид", "самоубий", "самоповрежд"} {
		if strings.HasPrefix(w, stem) {
			return CategorySuicide, true
		}
	}

	// 1. Наркотики ст. 6.13 КоАП РФ
	if _, ok := drugWordsSet[w]; ok {
		return CategoryDrugCoAP, true
	}

	// 2. Точный мат
	if _, ok := profanityExactSet[w]; ok {
		return CategoryProfane, true
	}

	// 3. Маркеры цензуры / эвфемизмы
	if _, ok := suspectMarkersSet[w]; ok {
		return CategorySuspect, true
	}

	// 4. Проверка корня 'еб'/'ёб' с исключением безопасных слов
	if strings.Contains(w, "еб") || strings.Contains(w, "ёб") {
		isSafe := false
		for _, safe := range safeEbSubstrings {
			if strings.Contains(w, safe) {
				isSafe = true
				break
			}
		}
		if !isSafe {
			return CategoryProfane, true
		}
	}

	// 5. Корни мата (хуй, пизд, бля, сука)
	for _, re := range profanityNonEbRegexes {
		if re.MatchString(w) {
			return CategoryProfane, true
		}
	}

	return "", false
}
